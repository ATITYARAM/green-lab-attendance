drop policy if exists "lab students self read" on public.lab_students;
create policy "lab students self read"
on public.lab_students for select to authenticated
using (auth_user_id = auth.uid());

drop policy if exists "lab devices self read" on public.lab_devices;
create policy "lab devices self read"
on public.lab_devices for select to authenticated
using (
  exists (
    select 1 from public.lab_students s
    where s.id = lab_devices.student_id
      and s.auth_user_id = auth.uid()
  )
);

drop policy if exists "lab attendance self read" on public.lab_attendance;
create policy "lab attendance self read"
on public.lab_attendance for select to authenticated
using (
  exists (
    select 1 from public.lab_students s
    where s.id = lab_attendance.student_id
      and s.auth_user_id = auth.uid()
  )
);

